-- Tablas Data Base (Metadatos y Estructura)

-- 1. PROFILES

create table public.profiles (
  id integer generated by default as identity not null,
  full_name character varying(100) not null,
  location character varying(150) not null,
  phone character varying(20) not null,
  email character varying(100) not null,
  website character varying(100) null,
  created_at timestamp with time zone null default now(),
  constraint profiles_new_pkey primary key (id)
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_profiles_email on public.profiles using btree (email) TABLESPACE pg_default;

-- 2. PROFILES_TITLES

create table public.profiles_titles (
  id integer generated by default as identity not null,
  profile_id integer not null,
  is_default boolean not null default false,
  created_at timestamp with time zone null default now(),
  version character varying null,
  constraint profiles_titles_pkey primary key (id),
  constraint fk_profiles_titles_profile foreign KEY (profile_id) references profiles (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create index IF not exists idx_profiles_titles_profile_id on public.profiles_titles using btree (profile_id) TABLESPACE pg_default;

-- 3. SUMMARIES

create table public.summaries (
  id integer generated by default as identity not null,
  profile_id integer null,
  is_default boolean null default false,
  created_at timestamp with time zone null default now(),
  version character varying null,
  constraint summaries_pkey primary key (id),
  constraint fk_summaries_profile foreign KEY (profile_id) references profiles (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

-- 4. SKILL_TYPES

create table public.skill_types (
  id integer generated by default as identity not null,
  slug character varying(50) not null,
  created_at timestamp with time zone null default now(),
  context text null,
  constraint skill_types_pkey primary key (id)
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_skill_types_slug on public.skill_types using btree (slug) TABLESPACE pg_default;

-- 5. SKILLS

create table public.skills (
  id integer generated by default as identity not null,
  profile_id integer not null,
  type_id integer null,
  is_active boolean null default true,
  created_at timestamp with time zone null default now(),
  constraint skills_new_pkey1 primary key (id),
  constraint fk_skills_profile foreign KEY (profile_id) references profiles (id) on delete CASCADE deferrable,
  constraint fk_skills_type foreign KEY (type_id) references skill_types (id) on delete set null
) TABLESPACE pg_default;

-- 6. EXPERIENCES

create table public.experiences (
  id integer generated by default as identity not null,
  profile_id integer null,
  company character varying(100) not null,
  start_date date not null,
  end_date date null,
  url text null,
  is_active boolean null default true,
  created_at timestamp with time zone null default now(),
  location character varying(100) null,
  constraint experiences_pkey primary key (id),
  constraint fk_experiences_profile foreign KEY (profile_id) references profiles (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

-- 7. RESPONSIBILITIES

create table public.responsibilities (
  id integer generated by default as identity not null,
  experience_id integer null,
  created_at timestamp with time zone null default now(),
  constraint responsibilities_pkey primary key (id),
  constraint fk_responsibilities_experience foreign KEY (experience_id) references experiences (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

-- 8. EDUCATION_TYPES

create table public.education_types (
  id integer generated by default as identity not null,
  slug character varying(50) not null,
  created_at timestamp with time zone null default now(),
  constraint education_types_pkey primary key (id)
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_education_types_slug on public.education_types using btree (slug) TABLESPACE pg_default;

-- 9. EDUCATION

create table public.education (
  id integer generated by default as identity not null,
  profile_id integer null,
  type_id integer null,
  start_date date null,
  end_date date null,
  url text null,
  is_active boolean null default true,
  created_at timestamp with time zone null default now(),
  institution character varying(150) not null default ''::character varying,
  location character varying(100) null,
  constraint education_pkey primary key (id),
  constraint fk_education_profile foreign KEY (profile_id) references profiles (id) on delete CASCADE deferrable,
  constraint fk_education_type foreign KEY (type_id) references education_types (id) on delete set null
) TABLESPACE pg_default;

-- Tablas de Traducciones (Contenido literario)

-- 1. PROFILES_TITLES_TRANSLATIONS

create table public.profiles_titles_translations (
  id integer generated by default as identity not null,
  title_id integer not null,
  language_code character(2) not null,
  content text not null,
  created_at timestamp with time zone null default now(),
  constraint profiles_titles_translations_pkey primary key (id),
  constraint fk_profiles_titles_translations_title foreign KEY (title_id) references profiles_titles (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create index IF not exists idx_profiles_titles_trans_title_id on public.profiles_titles_translations using btree (title_id) TABLESPACE pg_default;

create unique INDEX IF not exists idx_profiles_titles_trans_title_lang on public.profiles_titles_translations using btree (title_id, language_code) TABLESPACE pg_default;

-- 2. SUMMARIES_TRANSLATIONS

create table public.summaries_translations (
  id integer generated by default as identity not null,
  summary_id integer null,
  language_code character(2) not null,
  content text not null,
  created_at timestamp with time zone null default now(),
  constraint summaries_translations_pkey primary key (id),
  constraint fk_summaries_trans_summary foreign KEY (summary_id) references summaries (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_summaries_trans_summary_lang on public.summaries_translations using btree (summary_id, language_code) TABLESPACE pg_default;

-- 3. SKILL_TRANSLATIONS

create table public.skill_translations (
  id integer generated by default as identity not null,
  skill_id integer null,
  language_code character(2) not null,
  name character varying(100) not null,
  created_at timestamp with time zone null default now(),
  constraint skill_translations_pkey primary key (id),
  constraint fk_skill_trans_skill foreign KEY (skill_id) references skills (id) on delete CASCADE
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_skill_trans_skill_lang on public.skill_translations using btree (skill_id, language_code) TABLESPACE pg_default;

-- 4. EXPERIENCES_TRANSLATIONS

create table public.experiences_translations (
  id integer generated by default as identity not null,
  experience_id integer null,
  language_code character(2) not null,
  "position" character varying(100) not null,
  created_at timestamp with time zone null default now(),
  constraint experiences_translations_pkey primary key (id),
  constraint fk_experiences_trans_experience foreign KEY (experience_id) references experiences (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_experiences_trans_exp_lang on public.experiences_translations using btree (experience_id, language_code) TABLESPACE pg_default;

-- 5. RESPONSIBILITIES_TRANSLATIONS

create table public.responsibilities_translations (
  id integer generated by default as identity not null,
  responsibility_id integer null,
  language_code character(2) not null,
  description text not null,
  created_at timestamp with time zone null default now(),
  constraint responsibilities_translations_pkey primary key (id),
  constraint responsibilities_translations_responsibility_id_language_co_key unique (responsibility_id, language_code),
  constraint fk_responsibilities_trans_resp foreign KEY (responsibility_id) references responsibilities (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_responsibilities_trans_resp_lang on public.responsibilities_translations using btree (responsibility_id, language_code) TABLESPACE pg_default;

-- 6. EDUCATION_TRANSLATIONS

create table public.education_translations (
  id integer generated by default as identity not null,
  education_id integer null,
  language_code character(2) not null,
  title character varying(150) not null,
  created_at timestamp with time zone null default now(),
  top_badges text[] null,
  bottom_badges text[] null,
  constraint education_translations_pkey primary key (id),
  constraint fk_education_trans_education foreign KEY (education_id) references education (id) on delete CASCADE deferrable
) TABLESPACE pg_default;

create unique INDEX IF not exists idx_education_trans_edu_lang on public.education_translations using btree (education_id, language_code) TABLESPACE pg_default;